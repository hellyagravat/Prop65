// ============================================
// PROP65 SHIELD — WARNING TEXT GENERATOR
// ============================================
// Produces Prop 65 short-form and long-form
// warning text per 27 CCR § 25603.
//
// Pure functions. No network. No DOM.
// ============================================

(function (global) {
  'use strict';

  var P65_URL = 'www.P65Warnings.ca.gov';
  var WARNING_SYMBOL = '\u26A0'; // ⚠

  // --------------------------------------------
  // HAZARD LANGUAGE
  // --------------------------------------------

  function hazardPhrase(hazard) {
    switch ((hazard || '').toLowerCase()) {
      case 'cancer':
        return 'cancer';
      case 'reproductive':
        return 'birth defects or other reproductive harm';
      case 'both':
      default:
        return 'cancer and birth defects or other reproductive harm';
    }
  }

  // --------------------------------------------
  // COMBINE MULTIPLE CHEMICALS
  // --------------------------------------------

  function combineHazards(chemicals) {
    var hasCancer = false;
    var hasRepro = false;

    chemicals.forEach(function (c) {
      var h = (c.hazard || '').toLowerCase();
      if (h === 'cancer' || h === 'both') hasCancer = true;
      if (h === 'reproductive' || h === 'both') hasRepro = true;
    });

    if (hasCancer && hasRepro) return 'both';
    if (hasCancer) return 'cancer';
    if (hasRepro) return 'reproductive';
    return 'both';
  }

  // --------------------------------------------
  // CHEMICAL PHRASE
  // --------------------------------------------

  function chemicalPhrase(chemicals) {
    var names = chemicals.map(function (c) { return c.name; });

    if (names.length === 0) return '';
    if (names.length === 1) return names[0];
    if (names.length === 2) return names[0] + ' and ' + names[1];
    if (names.length === 3) {
      return names[0] + ', ' + names[1] + ', and ' + names[2];
    }

    var last = names.pop();
    return names.join(', ') + ', or ' + last;
  }

  // --------------------------------------------
  // SHORT FORM
  // --------------------------------------------

  function shortForm(chemicals) {
    if (!chemicals || !chemicals.length) return '';

    var phrase = chemicalPhrase(chemicals);
    var hazard = hazardPhrase(combineHazards(chemicals));

    return WARNING_SYMBOL + ' WARNING: ' +
      'This product can expose you to chemicals including ' +
      phrase + ', which is known to the State of California to cause ' +
      hazard + '. For more information go to ' + P65_URL + '.';
  }

  // --------------------------------------------
  // LONG FORM
  // --------------------------------------------

  function longForm(chemicals) {
    return shortForm(chemicals);
  }

  // --------------------------------------------
  // PER-PRODUCT GENERATE
  // --------------------------------------------

  function generate(chemicals) {
    if (!chemicals || !chemicals.length) {
      return {
        ok: false,
        reason: 'no_chemicals',
        short: '',
        long: '',
        hazard: null,
        chemicals: []
      };
    }

    return {
      ok: true,
      short: shortForm(chemicals),
      long: longForm(chemicals),
      hazard: combineHazards(chemicals),
      chemicals: chemicals.slice()
    };
  }

  // --------------------------------------------
  // DISCLAIMER
  // --------------------------------------------

  var DISCLAIMER =
    'This warning was generated by Prop65 Shield based on the ' +
    'ingredients you declared and the current OEHHA chemical list. ' +
    'It is not legal advice. Whether your specific product requires ' +
    'a warning depends on exposure levels that only testing or ' +
    'qualified counsel can determine.';

  // --------------------------------------------
  // PUBLIC API
  // --------------------------------------------

  global.Prop65WarningGen = {
    generate: generate,
    shortForm: shortForm,
    longForm: longForm,
    hazardPhrase: hazardPhrase,
    combineHazards: combineHazards,
    chemicalPhrase: chemicalPhrase,
    DISCLAIMER: DISCLAIMER,
    P65_URL: P65_URL
  };

})(window);